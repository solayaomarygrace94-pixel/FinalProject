    private void increesingActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_increesingActionPerformed
        // TODO add your handling code here:
        DefaultTableModel model =
            (DefaultTableModel) jTable1.getModel();

    TableRowSorter<DefaultTableModel> sorter =
            new TableRowSorter<>(model);

    jTable1.setRowSorter(sorter);

    sorter.setSortKeys(Collections.singletonList(
            new RowSorter.SortKey(0,
                    javax.swing.SortOrder.ASCENDING)));

    sorter.sort();

    }//GEN-LAST:event_increesingActionPerformed

    private void jButtonSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSaveActionPerformed
        // TODO add your handling code here:
        String description = jTextPane1.getText().trim();
    String dateCreated = jTextField5.getText().trim();
    String deadline = jTextField6.getText().trim();
    String status = jTextField7.getText().trim();

    if (description.isEmpty() || dateCreated.isEmpty()
            || deadline.isEmpty() || status.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please fill in all fields!");
        return;
    }

    DefaultTableModel model =
            (DefaultTableModel) jTable1.getModel();

    model.addRow(new Object[]{
        description, dateCreated, deadline, status
    });

    JOptionPane.showMessageDialog(this, "Task saved successfully!");

    jTextPane1.setText("");
    jTextField5.setText("");
    jTextField6.setText("");
    jTextField7.setText("");

    }//GEN-LAST:event_jButtonSaveActionPerformed

    private void EditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EditActionPerformed
        // TODO add your handling code here:
        int row = jTable1.getSelectedRow();

    if (row == -1) {
        JOptionPane.showMessageDialog(this,
                "Please select a task from the table!");
        return;
    }

    String description = jTextPane1.getText().trim();
    String dateCreated = jTextField5.getText().trim();
    String deadline = jTextField6.getText().trim();
    String status = jTextField7.getText().trim();

    if (description.isEmpty() || dateCreated.isEmpty()
            || deadline.isEmpty() || status.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please fill in all fields!");
        return;
    }

    int modelRow = jTable1.convertRowIndexToModel(row);
    DefaultTableModel model =
            (DefaultTableModel) jTable1.getModel();

    model.setValueAt(description, modelRow, 0);
    model.setValueAt(dateCreated, modelRow, 1);
    model.setValueAt(deadline, modelRow, 2);
    model.setValueAt(status, modelRow, 3);

    JOptionPane.showMessageDialog(this, "Task updated successfully!");

    }//GEN-LAST:event_EditActionPerformed

    private void DeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteActionPerformed
        // TODO add your handling code here:
         int row = jTable1.getSelectedRow();

    if (row == -1) {
        JOptionPane.showMessageDialog(this,
                "Please select a task to delete!");
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(this,
            "Are you sure you want to delete this task?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION);

    if (confirm == JOptionPane.YES_OPTION) {
        int modelRow = jTable1.convertRowIndexToModel(row);

        DefaultTableModel model =
                (DefaultTableModel) jTable1.getModel();

        model.removeRow(modelRow);

        JOptionPane.showMessageDialog(this,
                "Task deleted successfully!");
    }

        
    }//GEN-LAST:event_DeleteActionPerformed

